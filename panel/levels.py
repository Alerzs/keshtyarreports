def level_for(profit):
    found = None
    for level in SPECIALIST_LEVELS:
        if profit >= level['min']:
            found = level
    return found


def next_level(level):
    if level is None:
        return SPECIALIST_LEVELS[0]
    for item in SPECIALIST_LEVELS:
        if item['n'] == level['n'] + 1:
            return item
    return None


def perks_up_to(level):
    if not level:
        return []
    perks = []
    for item in SPECIALIST_LEVELS:
        if item['n'] <= level['n']:
            perks.extend(item['perks'])
    return perks


def payout(profit):
    level = level_for(profit)
    commission = int(profit * level['rate']) if level else 0
    bonus = level['bonus'] if level else 0
    return {
        'level': level,
        'commission': commission,
        'bonus': bonus,
        'base': BASE_SALARY,
        'total': BASE_SALARY + commission + bonus,
    }
